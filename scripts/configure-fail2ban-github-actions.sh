#!/usr/bin/env bash
# Add GitHub Actions runner IP ranges to fail2ban sshd ignoreip (so CI deploy SSH is not banned).
# Run on the app server as root:
#   sudo EXTRA_IGNORE_IPS="203.0.113.10" bash configure-fail2ban-github-actions.sh
#
# Optional cron (weekly): refresh ranges when GitHub updates meta.
#   0 4 * * 0 root /path/to/configure-fail2ban-github-actions.sh

set -euo pipefail

if [[ "${EUID:-0}" -ne 0 ]]; then
  echo "Run as root." >&2
  exit 1
fi

command -v curl >/dev/null || { apt-get update -qq && apt-get install -y curl; }
command -v jq >/dev/null || { apt-get update -qq && apt-get install -y jq; }
command -v fail2ban-client >/dev/null || { apt-get update -qq && apt-get install -y fail2ban; }

META_URL="${GITHUB_META_URL:-https://api.github.com/meta}"
JAIL_DROPIN=/etc/fail2ban/jail.d/sshd-github-actions.local

echo "==> Fetch GitHub meta (actions IP ranges)"
ACTIONS_IPS=$(curl -fsSL "$META_URL" | jq -r '.actions[] | select(test("^[0-9]"))' | tr '\n' ' ')
if [[ -z "${ACTIONS_IPS// }" ]]; then
  echo "Failed to load actions IP ranges from ${META_URL}" >&2
  exit 1
fi

BASE_IGNORE="127.0.0.1/8 ::1"
EXTRA="${EXTRA_IGNORE_IPS:-}"

install -d -m 0755 /etc/fail2ban/jail.d
cat >"$JAIL_DROPIN" <<EOF
# Generated by configure-fail2ban-github-actions.sh — do not edit by hand.
# https://api.github.com/meta (actions IPv4 ranges) + local ignores.

[sshd]
enabled = true
ignoreip = ${BASE_IGNORE} ${EXTRA} ${ACTIONS_IPS}
EOF

chmod 0644 "$JAIL_DROPIN"
fail2ban-client reload 2>/dev/null || systemctl restart fail2ban
echo "==> Wrote ${JAIL_DROPIN} ($(wc -w <<<"${ACTIONS_IPS}") action CIDRs)"
fail2ban-client status sshd 2>/dev/null | head -5 || fail2ban-client status
